-- Run only against a disposable local Supabase database: supabase test db.
begin;
create extension if not exists pgtap with schema extensions;
set search_path=public,extensions;
select plan(27);
insert into auth.users(id,email) values
 ('11111111-1111-4111-8111-111111111111','owner@test.invalid'),
 ('22222222-2222-4222-8222-222222222222','other@test.invalid');
select set_config('request.jwt.claims','{"sub":"11111111-1111-4111-8111-111111111111","role":"service_role"}',true);
select public.provision_owner('11111111-1111-4111-8111-111111111111');
select is(public.normalize_username('https://instagram.com/Example/reels/?igsh=foo'),'example','normalizes profile URL');
select throws_ok($$select public.normalize_username('https://instagram.com/example/evil')$$,'22023','invalid_username','rejects arbitrary URL suffix');
select throws_ok($$select public.normalize_username('https://instagram.com/reel/ABC')$$,'22023','invalid_username','rejects content URL');
select ok((select reloptions @> array['security_invoker=true'] from pg_class where oid='public.reels_summary'::regclass),'summary view invoker security');
select ok(not has_table_privilege('authenticated','public.creators','INSERT'),'canonical writes denied');
select ok(not has_table_privilege('authenticated','public.app_settings','UPDATE'),'settings direct updates denied');
select ok(not has_function_privilege('authenticated','public.provision_owner(uuid)','EXECUTE'),'owner provisioning service only');
select ok(not has_function_privilege('authenticated','public.worker_claim_dispatch(uuid,boolean,text,text)','EXECUTE'),'dispatch service only');
select ok(not has_function_privilege('anon','public.query_reels(uuid,jsonb)','EXECUTE'),'anonymous RPC denied');
select set_config('request.jwt.claims','{"sub":"11111111-1111-4111-8111-111111111111","role":"authenticated"}',true);
set local role authenticated;
select ok(public.is_allowed_owner(),'configured owner permitted');
select public.create_workspace('Research','research');
select public.create_workspace('Second','second');
select is((select count(*)::integer from public.workspaces),2,'owner sees own workspaces');
select public.add_creator((select id from public.workspaces where slug='research'),'@Example');
select public.add_creator((select id from public.workspaces where slug='second'),'example');
select is((select count(*)::integer from public.creators),1,'canonical creator across workspaces');
select is((public.import_creators((select id from public.workspaces where slug='research'),'[{"username":"example"},{"username":"other_creator"},{"username":"other_creator"}]')->>'duplicates')::integer,2,'atomic import dedupe');
select is((select count(*)::integer from public.creators),2,'deduped import count');
select throws_ok($$select public.import_creators((select id from public.workspaces where slug='research'),'[{"username":"rollback_creator"},{"username":"bad handle"}]')$$,'22023','invalid_username','invalid import rolls back');
select is((select count(*)::integer from public.creators),2,'invalid import left no new creator');
select public.update_settings('{"capacity":2}');
select throws_ok($$select public.add_creator((select id from public.workspaces where slug='research'),'overflow')$$,'P0001','capacity_exceeded','transactional cap');
select throws_ok($$select public.query_reels((select id from public.workspaces where slug='research'),'{"limit":51}')$$,'22023','invalid_pagination','database pagination max50');
select throws_ok($$select public.query_reels((select id from public.workspaces where slug='research'),'{"from":"2020-01-01","to":"2026-01-01"}')$$,'22023','invalid_date_range','bounded database date range');
select throws_ok($$select public.update_settings('{"scraping_enabled":true}')$$,'22023','invalid_settings','browser cannot enable live scraping');
select throws_ok($$select public.enqueue_refresh((select id from public.workspaces where slug='research'),array['33333333-3333-4333-8333-333333333333'::uuid])$$,'42501','creator_not_in_workspace','refresh validates creator membership');
reset role;
select set_config('request.jwt.claims','{"sub":"22222222-2222-4222-8222-222222222222","role":"authenticated"}',true);
set local role authenticated;
select ok(not public.is_allowed_owner(),'unconfigured user denied');
select is((select count(*)::integer from public.workspaces),0,'other user workspace isolation');
select is((select count(*)::integer from public.creators),0,'other user canonical isolation');
select is((select count(*)::integer from public.workspace_members),0,'membership graph private');
select throws_ok($$select public.create_workspace('Bad','bad')$$,'42501','forbidden','other user cannot create workspace');
select throws_ok($$select public.get_bootstrap()$$,'42501','forbidden','bootstrap allowlist checked');
reset role;
select * from finish();
rollback;
